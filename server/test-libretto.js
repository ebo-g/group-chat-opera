import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { after, test } from 'node:test';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { join, sep } from 'node:path';
import { tmpdir } from 'node:os';
import { pathToFileURL } from 'node:url';
import { config } from './config.js';
import { makeLibretto } from './libretto.js';
import { parseChat, selectDramatic } from './parser.js';

const originalCacheDir = config.cacheDir;
const originalProvider = config.provider;
let temporaryDirectory;

after(async () => {
  config.cacheDir = originalCacheDir;
  config.provider = originalProvider;
  if (temporaryDirectory) await rm(temporaryDirectory, { recursive: true, force: true });
});

test('stub lyrics omit forced endings and old stub cache entries are bypassed', async () => {
  temporaryDirectory = await mkdtemp(join(tmpdir(), 'opera-libretto-test-'));
  config.cacheDir = pathToFileURL(`${temporaryDirectory}${sep}`);
  config.provider = 'stub';

  const senders = ['Mira', 'Noah', 'Iris'];
  const chatText = Array.from({ length: 18 }, (_, index) => {
    const minute = String(5 + index).padStart(2, '0');
    return `3/4/25, 9:${minute} PM - ${senders[index % senders.length]}: Message ${index} turns the story toward its ending.`;
  }).join('\n');
  const parsed = parseChat(chatText);
  const selected = selectDramatic(parsed, { maxSenders: config.maxSenders, limit: config.maxMessages });
  const oldKey = createHash('sha256')
    .update(JSON.stringify(['stub', '', selected.senders, selected.messages]))
    .digest('hex');
  await writeFile(join(temporaryDirectory, `${oldKey}.json`), JSON.stringify({ title: 'stale cached opera' }));

  const first = await makeLibretto(chatText);
  assert.equal(first.cached, false, 'a cached stub generated by the previous version should not be reused');
  const lyrics = first.libretto.scenes.flatMap((scene) => scene.lines.map((line) => line.lyric));
  assert.ok(lyrics.length > 0);
  assert.ok(lyrics.every((lyric) => !/(?:,\s*)(?:ah|oh)!$/i.test(lyric)), 'stub output should not add fixed vocal endings');

  const second = await makeLibretto(chatText);
  assert.equal(second.cached, true, 'the new stub result should still be cached');
  assert.deepEqual(second.libretto, first.libretto);
});